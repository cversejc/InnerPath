def correct_sources():
    replacements = {
        "先答应/迁就，自述": "迁就为自述；先答应为假设，待核对",
        "自述：先答应/迁就": "自述：迁就；假设：先答应",
        "先答应（自述）": "可能先答应（待核对）",
    }
    def walk(value):
        if isinstance(value, str):
            for a, b in replacements.items():
                value = value.replace(a, b)
            return value
        if isinstance(value, dict):
            return {k: walk(v) for k, v in value.items()}
        if isinstance(value, list):
            return [walk(v) for v in value]
        return value
    for stage in ("S2", "S3", "S4"):
        path = OUTPUT / f"{stage}.json"
        record = json.loads(path.read_text(encoding="utf-8"))
        record.setdefault("original_model_output", record["output"])
        record["output"] = walk(record["output"])
        if stage == "S2":
            for f in record["output"]["findings"]:
                if f["finding_key"] == "s2.cycle.activation_path":
                    for s in f["structured_data"]["steps"]:
                        if s["stage"] in {"短期结果", "长期重复", "防御"}:
                            s["status"] = "自述与假设分开，具体情境待核对" if s["stage"] != "短期结果" else "假设"
        note = "迁就是问卷自述；先答应与短期不适是待核对假设，修正混合标记。"
        if note not in record.setdefault("developer_review_notes", []):
            record["developer_review_notes"].append(note)
        save(path, record)


